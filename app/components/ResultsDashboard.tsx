"use client";

import { useState, useCallback } from "react";
import { motion } from "framer-motion";
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Legend,
} from "recharts";
import { jsPDF } from "jspdf";
import type { Evaluation, PathResult } from "../lib/types";

interface Props {
  evaluation: Evaluation;
  onBack: () => void;
}

const fmt = (n: number) => new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 }).format(n);
const fmtShort = (n: number) => {
  if (Math.abs(n) >= 10000000) return `₹${(n / 10000000).toFixed(2)}Cr`;
  if (Math.abs(n) >= 100000) return `₹${(n / 100000).toFixed(1)}L`;
  return fmt(n);
};
const ym = (m: number) => `${Math.floor(m / 12)}y ${m % 12}m`;

const colors: Record<string, string> = { prepay: "#059669", invest: "#2563eb", balanced: "#7c3aed" };

function toLakhs(n: number) { return `₹${(n / 100000).toFixed(1)}L`; }

function usePdfExport(evaluation: Evaluation) {
  const [exporting, setExporting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const handleExport = useCallback(() => {
    setError(null);
    setExporting(true);
    try {
      const { inputs, paths, winner } = evaluation;
      const pdf = new jsPDF("p", "mm", "a4");
      const pw = pdf.internal.pageSize.getWidth();
      const ph = pdf.internal.pageSize.getHeight();
      const margin = 20;
      let y = margin;

      function addLine() { y += 1; pdf.setDrawColor(200); pdf.line(margin, y, pw - margin, y); y += 4; }

      function text(t: string, size = 10, style: "normal" | "bold" = "normal") {
        pdf.setFont("helvetica", style);
        pdf.setFontSize(size);
        pdf.text(t, margin, y);
        y += size * 0.45;
      }

      function kv(label: string, val: string, size = 9) {
        pdf.setFont("helvetica", "normal"); pdf.setFontSize(size);
        const lw = pdf.getTextWidth(label + "  ");
        pdf.text(label, margin, y);
        pdf.setFont("helvetica", "bold");
        pdf.text(val, margin + lw, y);
        y += size * 0.45;
      }

      function checkPage() { if (y > ph - margin) { pdf.addPage(); y = margin + 10; } }

      const FMT = (n: number) => "₹" + Math.abs(n).toLocaleString("en-IN", { maximumFractionDigits: 0 });
      const YM = (m: number) => `${Math.floor(m / 12)}y ${m % 12}m`;

      // Title
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(18);
      pdf.setTextColor(30);
      pdf.text("Decide — Prepay vs Invest Report", margin, y); y += 10;
      pdf.setFont("helvetica", "normal"); pdf.setFontSize(8);
      pdf.setTextColor(150);
      pdf.text("Generated by Decide.app | " + new Date().toLocaleDateString("en-IN", { year: "numeric", month: "long", day: "numeric" }), margin, y);
      y += 8;
      addLine();

      // Your Loan
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(12); pdf.setTextColor(30);
      text("Loan Details", 12, "bold");
      pdf.setFont("helvetica", "normal"); pdf.setFontSize(9); pdf.setTextColor(80);
      kv("Loan Amount", FMT(inputs.principal));
      kv("Interest Rate", `${inputs.annualRate}%`);
      kv("Tenure", `${inputs.tenureYears} years`);
      kv("Monthly Surplus", FMT(inputs.monthlySurplus));
      kv("Yearly Surplus", FMT(inputs.yearlySurplus));
      kv("One-time Surplus", FMT(inputs.lumpSum));
      kv("Expected Return", `${inputs.expectedReturnRate}%`);
      kv("Inflation", `${inputs.inflationRate}%`);
      kv("Tax Bracket", `${inputs.taxRate}%`);
      y += 2;
      addLine();

      // Recommendation
      checkPage();
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(14); pdf.setTextColor(5, 150, 105);
      text("Our Recommendation: " + winner.label, 14, "bold");
      pdf.setFont("helvetica", "normal"); pdf.setFontSize(9); pdf.setTextColor(60);
      text(winner.description, 9);
      y += 2;
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(10); pdf.setTextColor(30);
      kv("Payoff Time", YM(winner.payoffMonths));
      kv("Total Interest Paid", FMT(winner.totalInterest));
      kv("Interest Saved", FMT(winner.interestSaved));
      kv("Investment Value", FMT(winner.investmentValue));
      kv("Net Worth", FMT(winner.netWorth));
      kv("Net Benefit (post-tax)", FMT(winner.totalBenefit));
      y += 2;
      addLine();

      // Comparison table
      checkPage();
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(12); pdf.setTextColor(30);
      text("Strategy Comparison", 12, "bold");
      y += 1;

      const cols = ["Strategy", "Payoff", "Interest", "Investment", "Tax Saved", "Net Worth"];
      const colW = (pw - 2 * margin) / cols.length;
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(8); pdf.setTextColor(100);
      let cx = margin;
      cols.forEach(c => { pdf.text(c, cx, y, { align: c === "Strategy" ? "left" : "center" }); cx += colW; });
      y += 4;

      paths.forEach((p, i) => {
        checkPage();
        pdf.setFont("helvetica", i === 0 ? "bold" : "normal"); pdf.setFontSize(8);
        pdf.setTextColor(i === 0 ? 5 : 60, i === 0 ? 150 : 60, i === 0 ? 105 : 60);
        cx = margin;
        pdf.text(p.label, cx, y); cx += colW;
        pdf.text(YM(p.payoffMonths), cx, y, { align: "center" }); cx += colW;
        pdf.text(FMT(p.totalInterest), cx, y, { align: "center" }); cx += colW;
        pdf.text(p.investmentValue > 0 ? FMT(p.investmentValue) : "—", cx, y, { align: "center" }); cx += colW;
        pdf.text(FMT(p.taxBreakdown.totalTaxSaved), cx, y, { align: "center" }); cx += colW;
        pdf.text(FMT(p.netWorth), cx, y, { align: "center" }); cx += colW;
        y += 4;
      });
      y += 2;
      addLine();

      // Tax Breakdown
      checkPage();
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(12); pdf.setTextColor(30);
      text("Tax Impact (at " + inputs.taxRate + "% bracket)", 12, "bold");
      pdf.setFont("helvetica", "normal"); pdf.setFontSize(8); pdf.setTextColor(100);
      text("Section 24: Up to ₹2L/yr interest deductible. Section 80C: Up to ₹1.5L/yr principal deductible. LTCG: 10% on gains > ₹1L.", 8);
      y += 1;

      const tCols = ["Strategy", "Sec 24 Saved", "Sec 80C Saved", "LTCG Tax", "Post-Tax Benefit"];
      const tColW = (pw - 2 * margin) / tCols.length;
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(8); pdf.setTextColor(100);
      cx = margin;
      tCols.forEach(c => { pdf.text(c, cx, y, { align: c === "Strategy" ? "left" : "center" }); cx += tColW; });
      y += 4;

      paths.forEach((p, i) => {
        checkPage();
        pdf.setFont("helvetica", i === 0 ? "bold" : "normal"); pdf.setFontSize(8);
        pdf.setTextColor(i === 0 ? 5 : 60, i === 0 ? 150 : 60, i === 0 ? 105 : 60);
        cx = margin;
        pdf.text(p.label, cx, y); cx += tColW;
        pdf.text(FMT(p.taxBreakdown.section24Savings), cx, y, { align: "center" }); cx += tColW;
        pdf.text(FMT(p.taxBreakdown.section80CSavings), cx, y, { align: "center" }); cx += tColW;
        pdf.text(p.taxBreakdown.ltcgTax > 0 ? FMT(p.taxBreakdown.ltcgTax) : "—", cx, y, { align: "center" }); cx += tColW;
        pdf.text(FMT(p.totalBenefit), cx, y, { align: "center" }); cx += tColW;
        y += 4;
      });
      y += 2;
      addLine();

      // Inflation
      checkPage();
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(12); pdf.setTextColor(30);
      text("Inflation Reality Check (" + inputs.inflationRate + "% inflation)", 12, "bold");
      y += 1;
      const iCols = ["Strategy", "Nominal Net Worth", "Real Net Worth", "Loss to Inflation"];
      const iColW = (pw - 2 * margin) / iCols.length;
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(8); pdf.setTextColor(100);
      cx = margin;
      iCols.forEach(c => { pdf.text(c, cx, y, { align: c === "Strategy" ? "left" : "center" }); cx += iColW; });
      y += 4;
      paths.forEach((p, i) => {
        checkPage();
        pdf.setFont("helvetica", i === 0 ? "bold" : "normal"); pdf.setFontSize(8);
        pdf.setTextColor(i === 0 ? 5 : 60, i === 0 ? 150 : 60, i === 0 ? 105 : 60);
        cx = margin;
        pdf.text(p.label, cx, y); cx += iColW;
        pdf.text(FMT(p.netWorth), cx, y, { align: "center" }); cx += iColW;
        pdf.text(FMT(p.netWorthReal), cx, y, { align: "center" }); cx += iColW;
        pdf.text(FMT(p.netWorth - p.netWorthReal), cx, y, { align: "center" }); cx += iColW;
        y += 4;
      });
      y += 2;
      addLine();

      // What-If
      checkPage();
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(12); pdf.setTextColor(30);
      text("What-If Scenarios", 12, "bold");
      y += 1;
      evaluation.whatIfScenarios.forEach((s) => {
        checkPage();
        pdf.setFont("helvetica", "bold"); pdf.setFontSize(9); pdf.setTextColor(30);
        text(s.label + " (" + s.multiplier + "x surplus) → " + s.evaluation.winner.label, 9, "bold");
        pdf.setFont("helvetica", "normal"); pdf.setFontSize(8); pdf.setTextColor(80);
        kv("  Payoff", YM(s.evaluation.winner.payoffMonths));
        kv("  Net Worth", FMT(s.evaluation.winner.netWorth));
        kv("  Benefit", FMT(s.evaluation.winner.totalBenefit));
        y += 1;
      });
      y += 2;

      // Footer
      checkPage();
      addLine();
      pdf.setFont("helvetica", "normal"); pdf.setFontSize(8); pdf.setTextColor(150);
      text("Not financial advice. This is for educational purposes only. Consult a SEBI-registered advisor.", 8);
      text("Decide.app — prepay vs invest calculator", 8);

      pdf.save("Decide-Report.pdf");
    } catch (err) {
      console.error("PDF export failed:", err);
      setError("Could not generate PDF. Try again.");
    } finally {
      setExporting(false);
    }
  }, [evaluation]);
  return { handleExport, exporting, error, clearError: () => setError(null) };
}

