                <Line key={`${p.id}-real`} type="monotone" dataKey={`${p.label} (Real Worth)`} stroke={colors[p.tag]} strokeWidth={1} strokeDasharray="2 3" dot={false} name={`${p.emoji} ${p.label} (Real)`} opacity={0.5} />
